@app.get(
    "/api/v1/reports/patent-valuation",
    response_model=StoredReportListResponse,
    tags=["reports"],
)
def list_stored_patent_reports() -> dict[str, Any]:
    """미리 저장된 재평가 보고서 목록을 조회합니다.

    MinIO에서는 ``patents/{patent_id}/reports/{report_id}/report.json`` 구조를
    훑습니다. 로컬 fallback도 같은 구조를 우선 사용합니다.
    """
    reports: list[dict[str, Any]] = []
    seen: set[str] = set()

    if object_storage.enabled():
        for prefix in _report_list_prefix_candidates():
            for object_key in object_storage.list_object_keys(prefix):
                if not object_key.endswith("/report.json"):
                    continue
                patent_id, report_id = _extract_ids_from_report_key(object_key)
                key_id = f"{patent_id}:{report_id}" if patent_id and report_id else object_key
                if key_id in seen:
                    continue
                try:
                    if patent_id and report_id:
                        report, storage = _read_stored_report_by_ids(patent_id, report_id)
                    else:
                        payload = object_storage.get_json(object_key)
                        if not isinstance(payload, dict):
                            continue
                        report = _normalize_stored_report(payload)
                        storage = {
                            "backend": "minio",
                            "bucket": getattr(object_storage, "bucket", None),
                            "object_key": object_key,
                        }
                except HTTPException:
                    continue
                reports.append(_stored_report_summary(None, report, storage, patent_id=patent_id, report_id=report_id))
                seen.add(key_id)

    if PREBUILT_REPORT_DATA_DIR.exists():
        for report_path in sorted(PREBUILT_REPORT_DATA_DIR.glob(f"{_default_patent_prefix()}/*/reports/*/report.json")):
            patent_id = report_path.parents[2].name
            report_id = report_path.parent.name
            key_id = f"{patent_id}:{report_id}"
            if key_id in seen:
                continue
            try:
                report, storage = _read_stored_report_by_ids(patent_id, report_id)
            except HTTPException:
                continue
            reports.append(_stored_report_summary(None, report, storage, patent_id=patent_id, report_id=report_id))
            seen.add(key_id)

        for report_path in sorted(PREBUILT_REPORT_DATA_DIR.glob("*/report.json")):
            registration_number = report_path.parent.name
            if registration_number in seen:
                continue
            try:
                report, storage = _read_stored_report(registration_number)
            except HTTPException:
                continue
            reports.append(_stored_report_summary(registration_number, report, storage))

    return {"reports": reports}


@app.post(
    "/api/v1/reports/patent-valuation/generate",
    response_model=ReportGenerationResponse,
    tags=["reports"],
)
def generate_patent_report(request: ReportGenerationRequest) -> dict[str, Any]:
    """Generate report.json from parsed.json and store it in MinIO/local storage.

    This endpoint is intentionally synchronous for web/API driven integration
    tests. Production backend-triggered generation should use the RabbitMQ
    worker so long-running report work does not block a web request.
    """
    try:
        options = ReportGenerationOptions(
            profile=request.profile,
            enable_market=request.enable_market,
            enable_llm=request.enable_llm,
            enable_business_rag=request.enable_business_rag,
            similar_use_llm=request.similar_use_llm,
            rag_top_k=request.rag_top_k,
            output_key_template=request.output_key_template,
            local_output=request.local_output,
        )
        if object_storage.enabled() and not request.local_output and not request.report_id:
            raise HTTPException(status_code=400, detail="MinIO report.json 저장에는 reportId가 필요합니다.")
        service = ReportGenerationService(options)
        if request.patent is not None:
            return service.generate_from_patent(
                normalize_patent_input(request.patent),
                source=InputSource("inline", "inline"),
                report_id=request.report_id,
                patent_id=request.patent_id,
            )
        if request.parsed_object_key:
            return service.generate_from_source(
                InputSource("minio", request.parsed_object_key, object_key=request.parsed_object_key.strip("/")),
                report_id=request.report_id,
                patent_id=request.patent_id,
            )
        if request.local_path:
            path = Path(request.local_path)
            return service.generate_from_source(
                InputSource("local", str(path), path=path),
                report_id=request.report_id,
                patent_id=request.patent_id,
            )
        raise HTTPException(status_code=400, detail="patent, parsedObjectKey, localPath 중 하나는 필수입니다.")
    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(status_code=500, detail=str(exc)) from exc


@app.get(
    "/api/v1/reports/patent-valuation/patents/{patent_id}/reports/{report_id}",
    response_model=StoredReportResponse,
    tags=["reports"],
)
def get_stored_patent_report_by_ids(patent_id: str, report_id: str) -> dict[str, Any]:
    """patent ID와 report ID로 미리 저장된 재평가 report.json을 반환합니다."""
    normalized_patent_id = _normalize_storage_id(patent_id, "patent_id")
    normalized_report_id = _normalize_storage_id(report_id, "report_id")
    report, storage = _read_stored_report_by_ids(normalized_patent_id, normalized_report_id)
    patent = report.get("patent") if isinstance(report.get("patent"), dict) else {}
    return {
        "patent_id": normalized_patent_id,
        "report_id": normalized_report_id,
        "registration_number": patent.get("registration_number"),
        "report": report,
        "storage": storage,
    }


@app.get(
    "/api/v1/reports/patent-valuation/{registration_number}",
    response_model=StoredReportResponse,
    tags=["reports"],
)
def get_stored_patent_report(registration_number: str) -> dict[str, Any]:
    """특허 등록번호 또는 단일 patent ID로 미리 저장된 재평가 report.json을 반환합니다."""
    normalized = _normalize_registration_number(registration_number)
    report, storage = _read_stored_report(normalized)
    patent = report.get("patent") if isinstance(report.get("patent"), dict) else {}
    patent_id, report_id = _extract_ids_from_report_key(str(storage.get("object_key") or ""))
    return {
        "patent_id": patent_id,
        "report_id": report_id,
        "registration_number": patent.get("registration_number") or normalized,
        "report": report,
        "storage": storage,
    }


