PREBUILT_REPORT_DATA_DIR = _SRC_DIR.parent.parent / "data"


def _default_patent_prefix() -> str:
    return (os.getenv("MINIO_PATENT_PREFIX", "patents").strip("/") or "patents")


DEFAULT_REPORT_KEY_TEMPLATE = f"{_default_patent_prefix()}/{{patent_id}}/reports/{{report_id}}/report.json"


def _safe_name(value: str, fallback: str = "patent") -> str:
    cleaned = re.sub(r"[^0-9A-Za-z가-힣_.-]+", "_", str(value or "")).strip("._")
    return cleaned or fallback


def _timestamp() -> str:
    from datetime import datetime

    return datetime.now().strftime("%Y%m%d_%H%M%S")


def _normalize_registration_number(value: str) -> str:
    normalized = str(value or "").strip()
    if not normalized:
        raise HTTPException(status_code=400, detail="특허 등록번호는 필수입니다.")
    return normalized


def _normalize_storage_id(value: str | int, name: str) -> str:
    normalized = str(value or "").strip()
    if not normalized:
        raise HTTPException(status_code=400, detail=f"{name}는 필수입니다.")
    return normalized


def _stored_report_path(registration_number: str) -> Path:
    return PREBUILT_REPORT_DATA_DIR / _safe_name(registration_number) / "report.json"


def _stored_report_path_by_ids(patent_id: str, report_id: str) -> Path:
    return (
        PREBUILT_REPORT_DATA_DIR
        / _default_patent_prefix()
        / _safe_name(patent_id)
        / "reports"
        / _safe_name(report_id)
        / "report.json"
    )


def _add_storage_prefix_variants(keys: list[str]) -> list[str]:
    prefixes = [
        os.getenv("EVAL_LOGIC_REPORT_OBJECT_PREFIX", "").strip("/"),
        str(getattr(object_storage, "prefix", "") or "").strip("/"),
    ]
    rendered: list[str] = []
    for base_key in keys:
        base_key = base_key.strip("/")
        key_variants = [base_key]
        for prefix in prefixes:
            if prefix and not base_key.startswith(f"{prefix}/"):
                key_variants.append(f"{prefix}/{base_key}")
        for key in key_variants:
            if key not in rendered:
                rendered.append(key)
    return rendered


def _report_key_candidates(
    registration_number: str | None = None,
    patent_id: str | None = None,
    report_id: str | None = None,
) -> list[str]:
    template = os.getenv("EVAL_LOGIC_REPORT_OBJECT_KEY_TEMPLATE", DEFAULT_REPORT_KEY_TEMPLATE)
    raw_candidates = os.getenv("EVAL_LOGIC_REPORT_OBJECT_KEY_CANDIDATES", "")
    candidates = [template]
    if registration_number:
        candidates.extend(
            [
                "reports/{registration_number}/report.json",
                "{registration_number}/report.json",
                "patent/{registration_number}/report.json",
            ]
        )
    candidates.extend(item.strip() for item in raw_candidates.split(",") if item.strip())

    rendered_base: list[str] = []
    for candidate in candidates:
        if "{report_id}" in candidate and not report_id:
            continue
        base_key = candidate.format(
            registration_number=registration_number or patent_id or "",
            patent_id=patent_id or registration_number or "",
            report_id=report_id or "",
        ).strip("/")
        if base_key and base_key not in rendered_base:
            rendered_base.append(base_key)
    return _add_storage_prefix_variants(rendered_base)


def _report_prefix_candidates(patent_id: str) -> list[str]:
    return _add_storage_prefix_variants([f"{_default_patent_prefix()}/{patent_id}/reports/"])


def _extract_ids_from_report_key(object_key: str) -> tuple[str | None, str | None]:
    parts = object_key.strip("/").split("/")
    for index, part in enumerate(parts):
        if part == _default_patent_prefix() and len(parts) > index + 4 and parts[index + 2] == "reports":
            return parts[index + 1], parts[index + 3]
    return None, None


def _report_list_prefix_candidates() -> list[str]:
    base_prefix = os.getenv("EVAL_LOGIC_REPORT_LIST_PREFIX", f"{_default_patent_prefix()}/").lstrip("/")
    storage_prefix = str(getattr(object_storage, "prefix", "") or "").strip("/")
    prefixes = [base_prefix]
    if storage_prefix and not base_prefix.startswith(f"{storage_prefix}/"):
        prefixes.append(f"{storage_prefix}/{base_prefix}")
    return list(dict.fromkeys(prefixes))


def _normalize_stored_report(payload: dict[str, Any]) -> dict[str, Any]:
    """Normalize historical workflow outputs and current report JSON shape."""
    if payload.get("schema_version") == REPORT_SCHEMA_VERSION:
        return payload

    report = payload.get("report")
    if isinstance(report, dict) and report.get("schema_version") == REPORT_SCHEMA_VERSION:
        return report

    valuation = payload.get("valuation")
    if isinstance(valuation, dict):
        return build_structured_report(
            valuation,
            similar_analysis=payload.get("similar_analysis") if isinstance(payload.get("similar_analysis"), dict) else None,
            evaluation_analysis="",
        )

    if isinstance(report, dict):
        return report
    return payload


def _read_report_from_minio(
    registration_number: str | None = None,
    patent_id: str | None = None,
    report_id: str | None = None,
) -> tuple[dict[str, Any], str] | None:
    if not object_storage.enabled():
        return None
    errors: list[str] = []

    object_keys = _report_key_candidates(
        registration_number=registration_number,
        patent_id=patent_id,
        report_id=report_id,
    )
    if patent_id and not report_id:
        listed_keys: list[str] = []
        for prefix in _report_prefix_candidates(patent_id):
            listed_keys.extend(
                key
                for key in object_storage.list_object_keys(prefix)
                if key.endswith("/report.json")
            )
        object_keys.extend(sorted(dict.fromkeys(listed_keys), reverse=True))

    for object_key in dict.fromkeys(object_keys):
        try:
            payload = object_storage.get_json(object_key)
        except Exception as exc:
            errors.append(f"{object_key}: {exc}")
            continue
        if isinstance(payload, dict):
            return _normalize_stored_report(payload), object_key
    if errors and os.getenv("EVAL_LOGIC_REPORT_STRICT_MINIO", "false").lower() in {"1", "true", "yes"}:
        raise HTTPException(status_code=502, detail={"message": "MinIO report 조회 실패", "errors": errors})
    return None


def _read_report_json_file(path: Path) -> tuple[dict[str, Any], str] | None:
    if not path.exists():
        return None
    try:
        payload = json.loads(path.read_text(encoding="utf-8-sig"))
    except json.JSONDecodeError as exc:
        raise HTTPException(status_code=500, detail=f"저장된 보고서 JSON 파싱 실패: {exc}") from exc
    if not isinstance(payload, dict):
        raise HTTPException(status_code=500, detail="저장된 보고서 JSON 최상위 값은 object여야 합니다.")
    return _normalize_stored_report(payload), str(path)


def _read_report_from_local(registration_number: str) -> tuple[dict[str, Any], str] | None:
    return _read_report_json_file(_stored_report_path(registration_number))


def _read_report_from_local_by_ids(patent_id: str, report_id: str) -> tuple[dict[str, Any], str] | None:
    return _read_report_json_file(_stored_report_path_by_ids(patent_id, report_id))


def _read_stored_report_by_ids(patent_id: str, report_id: str) -> tuple[dict[str, Any], dict[str, Any]]:
    patent_id = _normalize_storage_id(patent_id, "patent_id")
    report_id = _normalize_storage_id(report_id, "report_id")

    minio_result = _read_report_from_minio(patent_id=patent_id, report_id=report_id)
    if minio_result:
        report, object_key = minio_result
        return report, {
            "backend": "minio",
            "bucket": getattr(object_storage, "bucket", None),
            "object_key": object_key,
        }

    local_result = _read_report_from_local_by_ids(patent_id, report_id)
    if local_result:
        report, path = local_result
        return report, {"backend": "local", "path": path}

    raise HTTPException(
        status_code=404,
        detail=f"저장된 재평가 보고서를 찾을 수 없습니다: patent_id={patent_id}, report_id={report_id}",
    )


def _read_stored_report(registration_number: str) -> tuple[dict[str, Any], dict[str, Any]]:
    registration_number = _normalize_registration_number(registration_number)

    minio_result = _read_report_from_minio(registration_number=registration_number, patent_id=registration_number)
    if minio_result:
        report, object_key = minio_result
        return report, {
            "backend": "minio",
            "bucket": getattr(object_storage, "bucket", None),
            "object_key": object_key,
        }

    local_result = _read_report_from_local(registration_number)
    if local_result:
        report, path = local_result
        return report, {"backend": "local", "path": path}

    raise HTTPException(
        status_code=404,
        detail=f"저장된 재평가 보고서를 찾을 수 없습니다: {registration_number}",
    )


def _stored_report_summary(
    registration_number: str | None,
    report: dict[str, Any],
    storage: dict[str, Any],
    patent_id: str | None = None,
    report_id: str | None = None,
) -> dict[str, Any]:
    patent = report.get("patent") if isinstance(report.get("patent"), dict) else {}
    registration_number = registration_number or patent.get("registration_number")
    if (not patent_id or not report_id) and storage.get("object_key"):
        key_patent_id, key_report_id = _extract_ids_from_report_key(str(storage["object_key"]))
        patent_id = patent_id or key_patent_id
        report_id = report_id or key_report_id
    report_url = (
        f"/api/v1/reports/patent-valuation/patents/{patent_id}/reports/{report_id}"
        if patent_id and report_id
        else f"/api/v1/reports/patent-valuation/{registration_number}"
    )
    return {
        "patent_id": patent_id,
        "report_id": report_id or report.get("report_id"),
        "registration_number": registration_number,
        "title": patent.get("title"),
        "schema_version": report.get("schema_version"),
        "generated_at": report.get("generated_at"),
        "report_url": report_url,
        "storage": storage,
    }


def _save_uploaded_pdf(file: UploadFile) -> Path:
    original_name = Path(file.filename or "patent.pdf").name
    safe_name = _safe_name(original_name, fallback="patent.pdf")
    content_type = (file.content_type or "").lower()
    looks_like_pdf = safe_name.lower().endswith(".pdf") or content_type == "application/pdf"
    if not looks_like_pdf:
        raise HTTPException(
            status_code=400,
            detail=(
                "PDF 파일만 업로드할 수 있습니다. "
                f"filename={original_name!r}, content_type={file.content_type!r}"
            ),
        )
    if not safe_name.lower().endswith(".pdf"):
        safe_name = f"{safe_name}.pdf"

    API_TEST_PDF_UPLOAD_DIR.mkdir(parents=True, exist_ok=True)
    dest = API_TEST_PDF_UPLOAD_DIR / f"{_timestamp()}_{safe_name}"
    file.file.seek(0)
    with dest.open("wb") as output:
        shutil.copyfileobj(file.file, output)
    return dest


